function translateValue(value, locale) {
  if (locale === "en") return value;
  if (typeof value === "string") return french[value] || value;
  if (Array.isArray(value)) return value.map((item) => translateValue(item, locale));
  if (value && typeof value === "object") {
    if (value.$$typeof || value.render) return value;
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateValue(item, locale)]));
  }
  return value;
}

export function localize(value, locale) {
  return translateValue(value, locale);
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("portfolio-language") || "en");

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage: (nextLanguage) => {
      setLanguage(nextLanguage);
      localStorage.setItem("portfolio-language", nextLanguage);
    },
    t: (value) => translateValue(value, language),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
